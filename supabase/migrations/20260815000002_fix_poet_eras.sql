-- Reassign poets whose era contradicts their now-real century.
--
-- Phase 4 of #721, and only possible after 20260815000001 put dates on poets.
-- 194 poets holding 710 served poems sit outside any defensible century
-- window for the era the database gives them. Some are ordinary drift; some are
-- flatly impossible — Hafiz Ibrahim (d. 1932) filed أندلسي, Ibrahim Naji
-- (d. 1953) filed أموي, Ahmad al-Safi al-Najafi (d. 1977) filed مخضرم.
--
-- Two eras are NOT derived from century and are left alone unless a poet is
-- being moved INTO them on evidence:
--   أندلسي (7) is geographic. An 11th-century Andalusian and an 11th-century
--     Abbasid share a century and belong in different eras, so membership here
--     is decided by place (nisba or attested city), never by date.
--   مخضرم (6) is definitional — it means a life that straddled the arrival of
--     Islam, so it is pinned to the 6th/7th century. Its old stamp of 13 was a
--     bug, not a judgement. Root cause and its fix:
--     poetry_quality_and_curation/categorization/config.py ERA_CENTURY.
--
-- The full move list, with the century and the reason for each, is in
-- docs/data/poet-era-moves.csv.

