// Generates src/design-system/tokens.css from tokens.json (the single source).
import { readFileSync, writeFileSync } from 'node:fs';
const here = new URL('../src/design-system/', import.meta.url);
const t = JSON.parse(readFileSync(new URL('tokens.json', here), 'utf8'));
const vars = (prefix, obj) => Object.entries(obj).map(([k, v]) => `  --${prefix}${k}: ${v};`).join('\n');
let css = '/* Generated by scripts/build-tokens.mjs from tokens.json. Do not edit. */\n:root {\n';
css += [vars('brand-', t.brand), vars('era-', t.eras), vars('ground-', t.grounds), vars('font-', t.fonts),
  vars('verse-', t.verse), vars('radius-', t.radius), vars('motion-', t.motion)].join('\n');
css += '\n}\n';
for (const [page, colours] of Object.entries(t.pages)) {
  css += `${page === 'night' ? ':root, ' : ''}[data-page='${page}'] {\n${vars('c-', colours)}\n}\n`;
}
writeFileSync(new URL('tokens.css', here), css);
console.log('tokens.css written');
